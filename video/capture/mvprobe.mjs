import { openBrowser, wait } from './lib.mjs'
const { browser, page } = await openBrowser()
await page.goto('http://127.0.0.1:3857/#/live')
await wait(page, 3500)
await page.getByText(/^Coastline ·/).first().click()
await wait(page, 8000)
await page.mouse.move(600, 400)
await page.getByRole('button', { name: 'More', exact: true }).click()
await wait(page, 600)
await page.getByRole('menuitem', { name: 'Multiview' }).or(page.getByRole('button', { name: 'Multiview' })).first().click()
await wait(page, 2500)
await page.screenshot({ path: 'shots/mv1.png' })
console.log(await page.evaluate(() => [...document.querySelectorAll('button,[role=menuitem],[role=option]')].filter(e => e.offsetParent).map(e => `"${(e.innerText || e.getAttribute('aria-label') || '').trim().replace(/\s+/g, ' ').slice(0, 40)}"`).join(' | ')))
await browser.close()
