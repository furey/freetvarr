import { openBrowser, wait } from './lib.mjs'
const { browser, page } = await openBrowser()
await page.goto('http://127.0.0.1:3857/#/live')
await wait(page, 3500)
await page.getByText(/^Coastline ·/).first().click()
await wait(page, 12000)
await page.screenshot({ path: 'shots/live1.png' })
await page.mouse.move(600, 400)
await wait(page, 500)
console.log(await page.evaluate(() => [...document.querySelectorAll('button')].filter(e => e.offsetParent).map(e => `"${(e.innerText || e.getAttribute('aria-label') || '').trim().replace(/\s+/g, ' ').slice(0, 40)}"`).join(' | ')))
await page.getByRole('button', { name: /more/i }).last().click().catch((e) => console.log('nomore', e.message.slice(0, 80)))
await wait(page, 800)
await page.screenshot({ path: 'shots/live2.png' })
console.log(await page.evaluate(() => [...document.querySelectorAll('button,[role=menuitem]')].filter(e => e.offsetParent).map(e => `"${(e.innerText || e.getAttribute('aria-label') || '').trim().replace(/\s+/g, ' ').slice(0, 40)}"`).join(' | ')))
await browser.close()
